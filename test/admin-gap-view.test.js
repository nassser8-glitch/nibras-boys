'use strict';
/* =============================================================================
 * صفّ «🔒 سجلات خاصة» أمام المدير/الوكيل — وصفة صادقة + زر «تحديث الآن»
 * -----------------------------------------------------------------------------
 * القصة: ظهر للمدير في نافذة نقاط الطالب صفٌّ مبهم:
 * «🔒 سجلات خاصة — للمعلّمات الأخريات  -2» رغم أن المدير يرى كل الملاحظات.
 * الحقيقة: الفارق أمام المتميز (ADMIN/AGENT) ليس خصوصية زميلات — إنه محلية
 * قديمة على جهازه مقابل لقطة أشمل من الخادم (لم يسحب أحدث البيانات بعد، أو
 * اختلف خط البداية). نافذةُ النقاط كانت توصفه وصفاً كاذباً. الحل: وصف صادق
 * (سجلات أحدث على الخادم لم تبلغ هذا الجهاز بعد) + زر تحديث يسحب أحدث نسخة
 * ويعيد فتح النافذة بالسطور الفعلية، + تشخيص مقتضب بالأرقام الحاسمة.
 * لغير المتميز (معلم) يبقى الوصف القديم الصحيح: تخصيص فعلي لزميلاتها.
 * ========================================================================== */
const test = require('node:test');
const assert = require('node:assert');
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const SRC = fs.readFileSync(path.join(ROOT, 'public', 'index.html'), 'utf8');

test('1) المتميز يرى وصفاً صادقاً لا «خصوصية زميلات» وهمية', () => {
  assert.ok(SRC.includes("'سجلات أحدث على الخادم لم تبلغ هذا الجهاز بعد'"),
    'لا وصف صادق للفارق أمام المدير/الوكيل');
  // الوصف القديم الصحيح باقٍ لغير المتميز فقط
  assert.ok(SRC.includes("'سجلات خاصة — للمعلّمات الأخريات'"),
    'وصف خصوصية الزميلات لغير المتميز اختفى');
  // الشرط يفصّل: صادق للمتميز، حقيقي لغيرهم
  const i = SRC.indexOf('const gapLabel = privileged');
  assert.ok(i >= 0, 'التفرقة بين المتميز وغيره غير موجودة');
});

test('2) زر «تحديث الآن» يظهر للمتميز فقط وعند فارق حقيقي', () => {
  assert.ok(SRC.includes('const needRefresh = !!privileged && diff !== 0 && __serverEnabled() && __syncEnabled();'),
    'شرط الزر غائب');
  assert.ok(SRC.includes("onclick=\"__refreshPointsView('${studentId}')\""),
    'زر التحديث غير مربوط بالدالة');
  assert.ok(SRC.includes('تحديث الآن'), 'نص الزر غائب');
});

test('3) زر التحديث يسحب أحدث نسخة ويعيد فتح النافذة بالسطور الفعلية', () => {
  const i = SRC.indexOf('function __refreshPointsView(');
  assert.ok(i >= 0, 'الدالة مفقودة');
  const body = SRC.slice(i, i + 520);
  assert.ok(body.includes('await __syncPull(school);'), 'لا سحب لأحدث نسخة');
  assert.ok(body.includes('await __syncPush(school);'), 'لا دفعة بعد السحب');
  assert.ok(body.includes('showStudentPoints(studentId);'), 'لا إعادة فتح النافذة');
});

test('4) تشخيص مقتضب يعرض دور الجلسة والأرقام الحاسمة عند الفارق', () => {
  assert.ok(SRC.includes('const diagBox = (needRefresh && hiddenRow)'),
    'صندوق التشخيص غير مشروط بالفارق');
  assert.ok(SRC.includes('دورك: ${escapeHtml(meN?.role'),
    'لا يعرض دور الجلسة');
  assert.ok(SRC.includes('رصيد الخادم الحقيقي'),
    'لا يعرض رصيد الخادم في التشخيص');
  assert.ok(SRC.includes('${diagBox}'),
    'صندوق التشخيص غير مدرج في نافذة النقاط');
});